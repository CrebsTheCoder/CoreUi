package org.crebs.coreui.menu.render;

public enum MenuSkin {
    PANEL_DARK, PANEL_LIGHT, HEADER_DARK, HEADER_LIGHT,
    ROW_DARK, ROW_LIGHT, ROW_PRESSED_DARK, ROW_PRESSED_LIGHT,
    ROW_DISABLED_DARK, ROW_DISABLED_LIGHT, BUTTON, BUTTON_PRESSED,
    BUTTON_DISABLED_DARK, BUTTON_DISABLED_LIGHT, PRIMARY_DARK, PRIMARY_LIGHT,
    PRIMARY_PRESSED, TAB_DARK, TAB_LIGHT, TAB_PRESSED_DARK, TAB_PRESSED_LIGHT,
    TAB_SELECTED_DARK, TAB_SELECTED_LIGHT, SELECTION_STRIPE, TOGGLE_ON, TOGGLE_OFF,
    TOGGLE_DISABLED, SLIDER_TRACK, SLIDER_TRACK_DISABLED, SLIDER_FILL_DARK,
    SLIDER_FILL_LIGHT, DROPDOWN, DROPDOWN_PRESSED, DROPDOWN_OPTION,
    DROPDOWN_OPTION_SELECTED, DROPDOWN_OPTION_PRESSED, FOCUS, DIVIDER, BADGE,
    PROGRESS_TRACK, PROGRESS_FILL, DROPDOWN_OPTION_LIGHT,
    DROPDOWN_OPTION_SELECTED_LIGHT, DROPDOWN_OPTION_PRESSED_LIGHT;

    public char glyph() {
        return (char) ('\uE300' + ordinal());
    }

    public int popupVariant() {
        return switch (this) {
            case DROPDOWN_OPTION -> 0;
            case DROPDOWN_OPTION_LIGHT -> 1;
            case DROPDOWN_OPTION_SELECTED -> 2;
            case DROPDOWN_OPTION_SELECTED_LIGHT -> 3;
            case DROPDOWN_OPTION_PRESSED -> 4;
            case DROPDOWN_OPTION_PRESSED_LIGHT -> 5;
            case SELECTION_STRIPE -> 6;
            default -> throw new IllegalStateException("Skin is not a popup: " + this);
        };
    }
}
